#pragma once

//###### Start Quellcode MbcPcf8574.h #############################################################

#ifndef _MBCPCF8574_H_
#define _MBCPCF8574_H_     "V1.0.0 - 02.08.2026"

//------ Einbindung Bibliotheken ------------------------------------------------------------------

#include <Arduino.h>
#include "MbcI2cBus.h"

//------ Start globale Deklarationen --------------------------------------------------------------

    #define MBC_PCF8574_BASE_ADDRESS   0x20    // 7-Bit-Basisadresse PCF8574  (8-Bit-Form: 0x40)
    #define MBC_PCF8574A_BASE_ADDRESS  0x38    // 7-Bit-Basisadresse PCF8574A (8-Bit-Form: 0x70)

    enum MbcPcf8574Typ
    {
        MBC_PCF8574_TYP_8574  = 0,
        MBC_PCF8574_TYP_8574A = 1
    };

//------ Ende globale Deklarationen ---------------------------------------------------------------

//------ Start Klassendefinition MbcPcf8574 -------------------------------------------------------

    //* Klasse fuer <MbcPcf8574>
    //* Ein Objekt = ein physischer PCF8574 oder PCF8574A (8-Bit-I2C-Portexpander,
    //* quasibidirektional).

    class MbcPcf8574
    {
        public:

            //*************************************************************************************
            //* Konstruktor zur Deklaration von Objektvariablen                                   *
            //*************************************************************************************
            //* bus: zu nutzender I2C-Bus                                                         *
            //* adr: Bausteinnummer 0...7 (A2/A1/A0-Adresspins)                                   *
            //* typ: MBC_PCF8574_TYP_8574 oder MBC_PCF8574_TYP_8574A                              *
            //*************************************************************************************

            MbcPcf8574(MbcI2cBus &bus, uint8_t adr, MbcPcf8574Typ typ = MBC_PCF8574_TYP_8574);

            //*************************************************************************************
            //* Alle 8 Bit schreiben                                                              *
            //*************************************************************************************
            //* data: neuer Ausgabewert                                                           *
            //*************************************************************************************
            //* Return: true = Baustein antwortet mit ACK                                         *
            //*************************************************************************************

            bool write(uint8_t data);

            //*************************************************************************************
            //* Alle 8 Bit lesen                                                                  *
            //*************************************************************************************
            //* data: Zielvariable                                                                *
            //*************************************************************************************
            //* Return: true = Baustein antwortet mit ACK                                         *
            //*************************************************************************************

            bool read(uint8_t &data);

        private:

            MbcI2cBus *_bus;
            uint8_t    _address7;
    };

//------ Ende Klassendefinition MbcPcf8574 --------------------------------------------------------

#endif  /* _MBCPCF8574_H_ */

