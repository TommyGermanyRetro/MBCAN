#include "MbcPcf8574.h"

//------ Start Klasse MbcPcf8574 ------------------------------------------------------------------

    //*********************************************************************************************
    //* Konstruktor zur Deklaration von Objektvariablen                                           *
    //*********************************************************************************************
    //* bus: zu nutzender I2C-Bus                                                                 *
    //* adr: Bausteinnummer 0...7 (A2/A1/A0-Adresspins)                                           *
    //* typ: MBC_PCF8574_TYP_8574 oder MBC_PCF8574_TYP_8574A                                      *
    //*********************************************************************************************

    MbcPcf8574::MbcPcf8574(MbcI2cBus &bus, uint8_t adr, MbcPcf8574Typ typ)
        : _bus(&bus),
          _address7((typ == MBC_PCF8574_TYP_8574A ? MBC_PCF8574A_BASE_ADDRESS
                                                    : MBC_PCF8574_BASE_ADDRESS) + adr)
    {
    }

    //*********************************************************************************************
    //* Alle 8 Bit schreiben                                                                      *
    //*********************************************************************************************
    //* data: Ausgabewert                                                                         *
    //*********************************************************************************************
    //* Return: false bei I2C-Fehler                                                              *
    //*********************************************************************************************

    bool MbcPcf8574::write(uint8_t data)
    {
        return _bus->writeBytes(_address7, &data, 1);
    }

    //*********************************************************************************************
    //* Alle 8 Bit lesen                                                                          *
    //*********************************************************************************************
    //* data: Zielvariable                                                                        *
    //*********************************************************************************************
    //* Return: false bei I2C-Fehler                                                              *
    //*********************************************************************************************

    bool MbcPcf8574::read(uint8_t &data)
    {
        return _bus->readBytes(_address7, &data, 1);
    }

//------ Ende Klasse MbcPcf8574 -------------------------------------------------------------------

