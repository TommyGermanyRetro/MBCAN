#include "MbcAs5600.h"

//------ Start Klasse MbcAs5600 -------------------------------------------------------------------

    //*********************************************************************************************
    //* Konstruktor zur Deklaration von Objektvariablen                                           *
    //*********************************************************************************************
    //* bus: zu nutzender I2C-Bus                                                                 *
    //*********************************************************************************************

    MbcAs5600::MbcAs5600(MbcI2cBus &bus)
        : _bus(&bus)
    {
    }

    //*********************************************************************************************
    //* Ein 16-Bit-Registerpaar (High-/Low-Byte) auslesen                                         *
    //*********************************************************************************************
    //* regHi: Registeradresse High-Byte                                                          *
    //* regLo: Registeradresse Low-Byte                                                           *
    //*********************************************************************************************
    //* Return: zusammengesetzter 12-Bit-Wert (0 bei I2C-Fehler)                                  *
    //*********************************************************************************************

    uint16_t MbcAs5600::readRegister16(uint8_t regHi, uint8_t regLo)
    {
        uint8_t hi, lo;

        if (!_bus->readRegister(MBC_AS5600_ADDRESS, regHi, hi)) return 0;
        if (!_bus->readRegister(MBC_AS5600_ADDRESS, regLo, lo)) return 0;

        return (((uint16_t) hi << 8) | lo) & 0x0fff;
    }

    //*********************************************************************************************
    //* Rohdaten zum Winkel auslesen                                                              *
    //*********************************************************************************************
    //* Return: Rohdaten Winkel 12-Bit 0...4095                                                   *
    //*********************************************************************************************

    uint16_t MbcAs5600::getRawAngle()
    {
        return readRegister16(MBC_AS5600_RAW_ANG_HI, MBC_AS5600_RAW_ANG_LO);
    }

