    //*********************************************************************************************
    //* Display initialisieren                                                                    *
    //*********************************************************************************************
    //* Return: false bei I2C-Fehler                                                              *
    //*********************************************************************************************

    bool MbcSsd1306::begin()
    {
        // In Bloecken senden (Wire-Sendepuffer der Arduino-Cores, typ. 32...128 Byte,
        // soll durch die Kommandosequenz nicht bis an die Grenze ausgereizt werden).

        const uint8_t TOTAL = sizeof(INIT_CMDS);
        const uint8_t CHUNK = 8;

        uint8_t buf[1 + CHUNK];

        for (uint8_t sent = 0; sent < TOTAL; sent += CHUNK)
        {
            uint8_t remaining = (uint8_t) (TOTAL - sent);
            uint8_t count = (remaining < CHUNK) ? remaining : CHUNK;

            buf[0] = CMD_MODE;
            memcpy_P(&buf[1], &INIT_CMDS[sent], count);

            if (!_bus->writeBytes(MBC_SSD1306_ADDRESS, buf, (uint8_t) (1 + count))) return false;
        }

        return clear();
    }

    //*********************************************************************************************
    //* Bildschirm loeschen                                                                       *
    //*********************************************************************************************
    //* Return: false bei I2C-Fehler                                                              *
    //*********************************************************************************************

    bool MbcSsd1306::clear()
    {
        if (!gotoxy(0, 0)) return false;

        // GDDRAM in Bloecken loeschen (128 Spalten * 8 Pages = 1024 Byte), da der
        // Wire-Sendepuffer der Arduino-Cores (typ. 32...128 Byte) eine einzelne
        // Transaktion ueber alle 1024 Byte nicht zulaesst.

        const uint16_t TOTAL = 128 * 8;
        const uint8_t  CHUNK = 16;

        uint8_t buf[1 + CHUNK];
        buf[0] = DATA_MODE;

        for (uint8_t i = 1; i <= CHUNK; i++) buf[i] = 0x00;

        for (uint16_t sent = 0; sent < TOTAL; sent += CHUNK)
        {
            if (!_bus->writeBytes(MBC_SSD1306_ADDRESS, buf, sizeof(buf))) return false;
        }

        return gotoxy(0, 0);
    }

    //*********************************************************************************************
